//! Acceptance tests for `specs/local-command-not-a-prompt` R2: the background walk and
//! D27's hand-back skip see through a local command (D4, D5, D9).
//!
//! Every case goes through the public boundary, `ai_monitor::activity::tail_state`, over a
//! log written to a temp file. Records follow the spec's Requirements shorthand (caveat,
//! U-wrapper, U-output, skill) and R2's background start / completion shapes, each stamped
//! with `timestamp`, `sessionId` and `uuid` like a real record.

use std::path::PathBuf;

use ai_monitor::activity::{tail_state, LastMessage, TAIL_CAP};
use serde_json::{json, Value};

use LastMessage::{AssistantBusy, AssistantEndTurn};

const B1: &str = "b1";
const A1: &str = "a1";

// ---- harness ----

fn body(records: &[Value]) -> String {
    let mut out = String::new();
    for (i, r) in records.iter().enumerate() {
        out.push_str(&stamp(r.clone(), i).to_string());
        out.push('\n');
    }
    out
}

/// Adds the bookkeeping fields every real record carries.
fn stamp(mut r: Value, i: usize) -> Value {
    if let Some(obj) = r.as_object_mut() {
        obj.entry("timestamp")
            .or_insert_with(|| json!(format!("2026-11-14T23:{:02}:{:02}.000Z", i / 60, i % 60)));
        obj.entry("sessionId")
            .or_insert_with(|| json!("4f6c2a8e-1b3d-4e5f-9a7b-0c1d2e3f4a5b"));
        obj.entry("uuid")
            .or_insert_with(|| json!(format!("00000000-0000-4000-8000-{i:012}")));
    }
    r
}

fn write(tag: &str, bytes: &[u8]) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("aimon-tt2-local-cmd-{}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("mkdir");
    let p = dir.join(format!("{tag}.jsonl"));
    std::fs::write(&p, bytes).expect("write");
    p
}

fn last(tag: &str, records: &[Value]) -> Option<LastMessage> {
    tail_state(&write(tag, body(records).as_bytes()))
        .expect("tail")
        .last
}

// ---- record helpers (the spec's Requirements shorthand) ----

fn human(text: &str) -> Value {
    json!({"type": "user", "origin": {"kind": "human"},
           "message": {"role": "user", "content": text}})
}

fn tool_use(name: &str) -> Value {
    json!({"type": "assistant", "message": {"role": "assistant", "stop_reason": "tool_use",
           "content": [{"type": "tool_use", "id": "toolu_01", "name": name, "input": {}}]}})
}

fn end_turn() -> Value {
    json!({"type": "assistant", "message": {"role": "assistant", "stop_reason": "end_turn",
           "content": [{"type": "text", "text": "Done."}]}})
}

fn result_with(result: Value) -> Value {
    json!({"type": "user", "toolUseResult": result,
           "message": {"role": "user", "content": [
               {"type": "tool_result", "tool_use_id": "toolu_01", "content": "ok"}]}})
}

/// Background start: `toolUseResult.backgroundTaskId` with a `tool_result` block.
fn bg_start(id: &str) -> Value {
    result_with(json!({"stdout": "", "backgroundTaskId": id}))
}

/// Background `Agent` launch.
fn agent_launch(id: &str) -> Value {
    result_with(json!({"isAsync": true, "status": "async_launched", "agentId": id}))
}

/// Completion: a `queue-operation` `enqueue` whose content begins
/// `<task-notification> <task-id>{id}</task-id>`.
fn completion(id: &str) -> Value {
    json!({"type": "queue-operation", "operation": "enqueue",
           "content": format!(
               "<task-notification> <task-id>{id}</task-id> <status>completed</status> \
                </task-notification>")})
}

fn caveat() -> Value {
    json!({"type": "user", "isMeta": true, "message": {"role": "user", "content":
        "<local-command-caveat>Caveat: The messages below were generated by the user while \
         running local commands. DO NOT respond to these messages or otherwise consider them \
         in your response unless the user explicitly asks you to.</local-command-caveat>"}})
}

fn u_wrapper(cmd: &str) -> Value {
    json!({"type": "user", "message": {"role": "user", "content": format!(
        "<command-name>/{cmd}</command-name>\n            <command-message>{cmd}</command-message>\n            <command-args></command-args>")}})
}

fn u_output(text: &str) -> Value {
    json!({"type": "user", "message": {"role": "user",
           "content": format!("<local-command-stdout>{text}</local-command-stdout>")}})
}

fn local_command(cmd: &str, out: &str) -> Vec<Value> {
    vec![caveat(), u_wrapper(cmd), u_output(out)]
}

/// skill(/s): the wrapper, then the skill body.
fn skill(s: &str) -> Vec<Value> {
    vec![
        json!({"type": "user", "origin": {"kind": "human"}, "message": {"role": "user",
               "content": format!("<command-message>{s}</command-message>\n<command-name>/{s}</command-name>")}}),
        json!({"type": "user", "isMeta": true, "message": {"role": "user", "content": [
               {"type": "text", "text": "Base directory for this skill: /x\n\n# Skill"}]}}),
    ]
}

/// `human prompt → assistant tool_use Bash → background start(b1) → end_turn`.
fn bash_turn() -> Vec<Value> {
    vec![
        human("run the slow thing"),
        tool_use("Bash"),
        bg_start(B1),
        end_turn(),
    ]
}

/// R2.5's prefix: a background Agent launch handed back, then its duplicate notification.
fn handback_prefix() -> Vec<Value> {
    vec![
        human("review the doc"),
        tool_use("Agent"),
        agent_launch(A1),
        json!({"type": "user", "isMeta": true,
               "origin": {"kind": "peer", "from": A1, "handback": true},
               "message": {"role": "user", "content":
                   "Another Claude session sent a message: <agent-message from=\"a1\">report"}}),
        end_turn(),
        json!({"type": "user", "origin": {"kind": "task-notification"},
               "message": {"role": "user", "content":
                   "<task-notification> <task-id>a1</task-id> <status>completed</status> </task-notification>"}}),
    ]
}

fn cat(parts: Vec<Vec<Value>>) -> Vec<Value> {
    parts.into_iter().flatten().collect()
}

// ---- R2 ----

#[test]
fn r2_1_pending_background_work_survives_a_local_command() {
    let log = cat(vec![
        bash_turn(),
        local_command("model", "Set model to opus"),
    ]);
    assert_eq!(last("r2_1", &log), Some(AssistantBusy));
}

#[test]
fn r2_2_finished_background_work_is_still_finished_across_a_local_command() {
    let log = cat(vec![
        bash_turn(),
        vec![completion(B1)],
        local_command("model", "Set model to opus"),
    ]);
    assert_eq!(last("r2_2", &log), Some(AssistantEndTurn));
}

#[test]
fn r2_3_a_skill_command_still_bounds_the_walk() {
    let log = cat(vec![bash_turn(), skill("s"), vec![end_turn()]]);
    assert_eq!(last("r2_3", &log), Some(AssistantEndTurn));
}

#[test]
fn r2_4_a_bang_command_still_bounds_the_walk() {
    let log = cat(vec![
        bash_turn(),
        vec![
            json!({"type": "user", "message": {"role": "user",
                   "content": "<bash-input>ls</bash-input>"}}),
            json!({"type": "user", "message": {"role": "user",
                   "content": "<bash-stdout>a</bash-stdout><bash-stderr></bash-stderr>"}}),
            end_turn(),
        ],
    ]);
    assert_eq!(last("r2_4", &log), Some(AssistantEndTurn));
}

#[test]
fn r2_5_a_handed_back_notification_is_skipped_through_a_local_command() {
    // The spec states the log without the local command already reads AssistantEndTurn.
    assert_eq!(
        last("r2_5_without", &handback_prefix()),
        Some(AssistantEndTurn),
        "precondition: D27 skips the handed-back notification"
    );
    let log = cat(vec![
        handback_prefix(),
        local_command("effort", "Set effort level to high"),
    ]);
    assert_eq!(last("r2_5", &log), Some(AssistantEndTurn));
}

#[test]
fn r2_6_a_handed_back_notification_behind_a_run_larger_than_the_tail() {
    let pad = "x".repeat(3 * 1024);
    let mut groups = Vec::new();
    while (body(&groups).len() as u64) <= TAIL_CAP {
        groups.extend(local_command(
            "effort",
            &format!("Set effort level to high {pad}"),
        ));
    }
    let prefix = handback_prefix();
    let n = prefix.len();
    let full = cat(vec![prefix, groups]);
    let text = body(&full);
    // The local-command groups alone (as stamped in the full log) exceed the tail.
    let group_bytes: usize = text.lines().skip(n).map(|l| l.len() + 1).sum();
    assert!(
        group_bytes as u64 > TAIL_CAP,
        "groups ({group_bytes} bytes) must exceed TAIL_CAP ({TAIL_CAP})"
    );
    let got = tail_state(&write("r2_6", text.as_bytes()))
        .expect("tail")
        .last;
    assert_eq!(got, Some(AssistantEndTurn));
}
