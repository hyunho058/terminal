#[test]
fn r1_7_a_wrapper_with_neither_marker_is_a_prompt() {
    let records = [human("fix the build"), end_turn(), u_wrapper("model")];
    assert_eq!(last("r1_7", &records), Some(UserPrompt));
}

#[test]
fn r1_8_non_turn_records_between_the_markers_and_the_wrapper_are_tolerated() {
    let records = [
        human("fix the build"),
        end_turn(),
        caveat(),
        attachment(),
        u_wrapper("model"),
        file_history_snapshot(),
        u_output(),
    ];
    assert_eq!(last("r1_8", &records), Some(AssistantEndTurn));
}

#[test]
fn r1_9_a_system_record_between_breaks_the_adjacency() {
    let records = [
        human("fix the build"),
        end_turn(),
        u_wrapper("model"),
        turn_duration(),
        u_output(),
    ];
    assert_eq!(
        last("r1_9", &records),
        Some(UserPrompt),
        "the wrapper is unmarked and the output record itself is skipped"
    );
}

#[test]
fn r1_10_a_stderr_output_marks_the_wrapper() {
    let records = [
        human("fix the build"),
        end_turn(),
        u_wrapper("model"),
        u_stderr(),
    ];
    assert_eq!(last("r1_10", &records), Some(AssistantEndTurn));
}

#[test]
fn r1_11_a_local_command_typed_mid_turn_reads_the_busy_turn() {
    let records = [
        human("run the tests"),
        tool_use_bash(),
        caveat(),
        u_wrapper("model"),
        u_output(),
    ];
    assert_eq!(last("r1_11", &records), Some(AssistantBusy));
}

#[test]
fn r1_12_two_local_commands_in_a_row() {
    let records = [
        human("fix the build"),
        end_turn(),
        caveat(),
        u_wrapper("model"),
        u_output(),
        caveat(),
        u_wrapper("effort"),
        u_output(),
    ];
    assert_eq!(last("r1_12", &records), Some(AssistantEndTurn));
}

#[test]
fn r1_13_a_half_written_line_after_a_local_command_still_reads_none() {
    let records = [
        human("fix the build"),
        end_turn(),
        caveat(),
        u_wrapper("model"),
        u_output(),
    ];
    let mut body = body_of(&records);
    body.push_str(r#"{"type":"assistant","mess"#); // no trailing newline
    let path = write("r1_13", body.as_bytes());
    assert_eq!(tail_state(&path).expect("tail").last, None);
}

#[test]
fn r1_14_a_fresh_clear_log_reads_none_with_role_system() {
    let records = [caveat(), u_wrapper("clear"), s_output()];
    let state = tail_state(&log("r1_14", &records)).expect("Some(state)");
    assert_eq!(state.last, None);
    assert_eq!(state.role, "system");
}
