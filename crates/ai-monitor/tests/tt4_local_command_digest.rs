//! TT4 — acceptance tests for `specs/local-command-not-a-prompt` R4 (D5, D6): the
//! overview digest neither opens nor closes a turn for a caveated Claude Code local
//! command, while a skill command and a caveat-less wrapper still open one.
//!
//! Every case folds Claude Code JSONL records through `SessionTelemetry::apply`, one record
//! per call, on an accumulator built `SessionTelemetry::new().with_digest()`, and reads
//! `snapshot()`'s `last_prompt_ms` and `turns` (newest first). Record shapes follow the
//! spec's Requirements shorthand (caveat, U-wrapper, U-output, skill, end_turn).

use ai_monitor::telemetry::SessionTelemetry;
use serde_json::{json, Value};

const SESSION: &str = "sess-tt4";

/// `2026-11-14T10:{min}:{sec}Z`.
fn stamp(min: u32, sec: u32) -> String {
    format!("2026-11-14T10:{min:02}:{sec:02}.000Z")
}

/// Epoch ms of [`stamp`].
fn ms(min: u32, sec: u32) -> u64 {
    // 2026-11-14T00:00:00Z
    const DAY_MS: u64 = 1_794_614_400_000;
    DAY_MS + 10 * 3_600_000 + u64::from(min) * 60_000 + u64::from(sec) * 1_000
}

fn uuid(tag: &str, min: u32, sec: u32) -> String {
    format!("00000000-0000-4000-8000-{tag}{min:02}{sec:02}")
}

/// A human prompt: `origin.kind: "human"`, plain text.
fn human(min: u32, text: &str) -> Value {
    json!({"type": "user", "timestamp": stamp(min, 0), "sessionId": SESSION,
           "uuid": uuid("aaaaaaaa", min, 0),
           "origin": {"kind": "human"},
           "message": {"role": "user", "content": text}})
}

/// An assistant record with `stop_reason: "end_turn"`.
fn end_turn(min: u32) -> Value {
    json!({"type": "assistant", "timestamp": stamp(min, 0), "sessionId": SESSION,
           "uuid": uuid("bbbbbbbb", min, 0),
           "message": {"id": format!("msg_end_{min}"), "role": "assistant",
                       "stop_reason": "end_turn",
                       "content": [{"type": "text", "text": "Done."}]}})
}

/// An assistant `tool_use` (Bash) — the turn is still running.
fn bash_call(min: u32) -> Value {
    json!({"type": "assistant", "timestamp": stamp(min, 0), "sessionId": SESSION,
           "uuid": uuid("cccccccc", min, 0),
           "message": {"id": format!("msg_tool_{min}"), "role": "assistant",
                       "stop_reason": "tool_use",
                       "content": [{"type": "tool_use", "id": format!("toolu_{min}"),
                                    "name": "Bash",
                                    "input": {"command": "cargo test",
                                              "description": "Run the tests"}}]}})
}

/// **caveat** — the `isMeta` user record Claude Code writes before a local command.
fn caveat(min: u32, sec: u32) -> Value {
    json!({"type": "user", "isMeta": true, "timestamp": stamp(min, sec), "sessionId": SESSION,
           "uuid": uuid("dddddddd", min, sec),
           "message": {"role": "user", "content":
               "<local-command-caveat>Caveat: The messages below were generated by the user \
                while running local commands. DO NOT respond to these messages or otherwise \
                consider them in your response unless the user explicitly asks you to.\
                </local-command-caveat>"}})
}

/// **U-wrapper(/x)** — a local command's `user` wrapper.
fn u_wrapper(min: u32, sec: u32, name: &str) -> Value {
    let content = format!(
        "<command-name>/{name}</command-name>\n            \
         <command-message>{name}</command-message>\n            \
         <command-args></command-args>"
    );
    json!({"type": "user", "timestamp": stamp(min, sec), "sessionId": SESSION,
           "uuid": uuid("eeeeeeee", min, sec),
           "message": {"role": "user", "content": content}})
}

/// **U-output** — a local command's `user` stdout record.
fn u_output(min: u32, sec: u32) -> Value {
    json!({"type": "user", "timestamp": stamp(min, sec), "sessionId": SESSION,
           "uuid": uuid("ffffffff", min, sec),
           "message": {"role": "user", "content":
               "<local-command-stdout>Set model to Opus</local-command-stdout>"}})
}

/// A non-turn `attachment` record (D7 tolerates it between caveat and wrapper).
fn attachment(min: u32, sec: u32) -> Value {
    json!({"type": "attachment", "timestamp": stamp(min, sec), "sessionId": SESSION,
           "uuid": uuid("abababab", min, sec),
           "attachment": {"type": "todo_reminder", "content": [], "itemCount": 0}})
}

/// **skill(/s)** — the wrapper (with `origin.kind: "human"`) then the `isMeta` skill body.
fn skill(min: u32, name: &str) -> [Value; 2] {
    [
        json!({"type": "user", "timestamp": stamp(min, 0), "sessionId": SESSION,
               "uuid": uuid("cdcdcdcd", min, 0),
               "origin": {"kind": "human"},
               "message": {"role": "user", "content":
                   format!("<command-message>{name}</command-message>\n<command-name>/{name}</command-name>")}}),
        json!({"type": "user", "isMeta": true, "timestamp": stamp(min, 1), "sessionId": SESSION,
               "uuid": uuid("efefefef", min, 1),
               "message": {"role": "user", "content": [
                   {"type": "text", "text": "Base directory for this skill: /x\n\n# Skill"}]}}),
    ]
}

fn digest() -> SessionTelemetry {
    SessionTelemetry::new().with_digest()
}

/// One `apply` call per record.
fn fold(t: &mut SessionTelemetry, records: &[Value]) {
    for r in records {
        t.apply(&r.to_string());
    }
}

// Times: t0 = 10:00, t1 = 10:01, t2 = 10:02, t3 = 10:03.

/// R4.1: `human (t0) → end_turn (t1)`, then `caveat, U-wrapper(/model), U-output` at t2 →
/// `last_prompt_ms == Some(t0)`, one turn, and it ended at t1.
#[test]
fn r4_1_local_command_after_finished_turn_moves_nothing() {
    let mut t = digest();
    fold(&mut t, &[human(0, "fix the bug"), end_turn(1)]);

    fold(
        &mut t,
        &[caveat(2, 0), u_wrapper(2, 0, "model"), u_output(2, 0)],
    );

    let s = t.snapshot();
    assert_eq!(
        s.last_prompt_ms,
        Some(ms(0, 0)),
        "last_prompt_ms stays at t0"
    );
    assert_eq!(s.turns.len(), 1, "no turn opened for /model: {:?}", s.turns);
    assert_eq!(
        s.turns[0].end_ms,
        Some(ms(1, 0)),
        "the turn still ended at t1"
    );
}

/// R4.2: `human (t0) → assistant tool_use (t1)` (no `end_turn`), then `caveat,
/// U-wrapper(/model), U-output` → one turn, still open, `last_prompt_ms == Some(t0)`.
#[test]
fn r4_2_local_command_during_open_turn_leaves_it_open() {
    let mut t = digest();
    fold(&mut t, &[human(0, "run the tests"), bash_call(1)]);

    fold(
        &mut t,
        &[caveat(2, 0), u_wrapper(2, 0, "model"), u_output(2, 0)],
    );

    let s = t.snapshot();
    assert_eq!(s.turns.len(), 1, "no turn opened for /model: {:?}", s.turns);
    assert_eq!(
        s.turns[0].end_ms, None,
        "the open turn is not closed by /model"
    );
    assert_eq!(
        s.last_prompt_ms,
        Some(ms(0, 0)),
        "last_prompt_ms stays at t0"
    );
}

/// R4.3: `human (t0) → end_turn (t1)`, then `caveat, attachment, U-wrapper(/model),
/// U-output`, each in its own call → `last_prompt_ms == Some(t0)`, one turn.
#[test]
fn r4_3_interleaved_records_do_not_disarm_the_caveat() {
    let mut t = digest();
    fold(&mut t, &[human(0, "fix the bug"), end_turn(1)]);

    fold(
        &mut t,
        &[
            caveat(2, 0),
            attachment(2, 0),
            u_wrapper(2, 0, "model"),
            u_output(2, 0),
        ],
    );

    let s = t.snapshot();
    assert_eq!(
        s.last_prompt_ms,
        Some(ms(0, 0)),
        "last_prompt_ms stays at t0"
    );
    assert_eq!(s.turns.len(), 1, "no turn opened for /model: {:?}", s.turns);
}

/// R4.4: `human (t0) → end_turn (t1)`, then `skill(/s)` (wrapper at t2, then its body) →
/// `last_prompt_ms == Some(t2)`, two turns, the newest (front) one open.
#[test]
fn r4_4_skill_command_opens_a_turn() {
    let mut t = digest();
    fold(&mut t, &[human(0, "fix the bug"), end_turn(1)]);

    fold(&mut t, &skill(2, "run-term"));

    let s = t.snapshot();
    assert_eq!(
        s.last_prompt_ms,
        Some(ms(2, 0)),
        "the skill command is a prompt at t2"
    );
    assert_eq!(
        s.turns.len(),
        2,
        "the skill command opened a turn: {:?}",
        s.turns
    );
    assert_eq!(s.turns[0].end_ms, None, "the front (newest) turn is open");
}

/// R4.5: `human (t0) → end_turn (t1) → caveat (t2)`, then a human prompt at t3 →
/// `last_prompt_ms == Some(t3)`, two turns.
#[test]
fn r4_5_caveat_followed_by_non_wrapper_disarms() {
    let mut t = digest();
    fold(
        &mut t,
        &[human(0, "fix the bug"), end_turn(1), caveat(2, 0)],
    );

    fold(&mut t, &[human(3, "now the other one")]);

    let s = t.snapshot();
    assert_eq!(
        s.last_prompt_ms,
        Some(ms(3, 0)),
        "the human prompt at t3 counts"
    );
    assert_eq!(
        s.turns.len(),
        2,
        "the human prompt opened a turn: {:?}",
        s.turns
    );
}

/// R4.6: `human (t0) → end_turn (t1)`, then `U-wrapper(/model) (t2)` and `U-output (t2)`
/// with no caveat → `last_prompt_ms == Some(t2)`, two turns, and the `U-output` opens no
/// further turn.
#[test]
fn r4_6_wrapper_without_caveat_still_opens_a_turn() {
    let mut t = digest();
    fold(&mut t, &[human(0, "fix the bug"), end_turn(1)]);

    fold(&mut t, &[u_wrapper(2, 0, "model")]);
    let after_wrapper = t.snapshot();
    assert_eq!(
        after_wrapper.turns.len(),
        2,
        "a caveat-less wrapper opens a turn: {:?}",
        after_wrapper.turns
    );

    fold(&mut t, &[u_output(2, 0)]);
    let s = t.snapshot();
    assert_eq!(
        s.last_prompt_ms,
        Some(ms(2, 0)),
        "last_prompt_ms moves to t2"
    );
    assert_eq!(
        s.turns.len(),
        2,
        "the U-output itself opens no further turn: {:?}",
        s.turns
    );
}
