//! Acceptance tests for `specs/local-command-not-a-prompt` R3 (D9): a run of local-command
//! records larger than the 8 KiB tail still finds the record before it.
//!
//! Every case goes through the public boundary, `ai_monitor::activity::tail_state`, over a
//! log written to a temp file. Records are built in the spec's Requirements shorthand
//! (`caveat`, `U-wrapper(/x)`, `U-output`), each carrying `timestamp`, `sessionId` and
//! `uuid` like a real one. R3.2 (the byte budget) is `(manual)` at this boundary and is
//! checked by T1's unit test inside `activity.rs`.

use std::path::PathBuf;

use ai_monitor::activity::{tail_state, LastMessage, TAIL_CAP};
use serde_json::{json, Value};

const SESSION: &str = "5b0c7e2a-3f41-4d8e-9a61-2c7d0e9b4f13";

fn write(tag: &str, body: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("aimon-tt3-local-cmd-{}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("mkdir");
    let p = dir.join(format!("{tag}.jsonl"));
    std::fs::write(&p, body).expect("write");
    p
}

fn lines(records: &[Value]) -> String {
    let mut body = String::new();
    for r in records {
        body.push_str(&r.to_string());
        body.push('\n');
    }
    body
}

/// Adds the bookkeeping fields every real record carries.
fn stamped(mut v: Value, n: usize) -> Value {
    let obj = v.as_object_mut().expect("record is an object");
    obj.insert(
        "timestamp".into(),
        json!(format!(
            "2026-11-14T23:{:02}:{:02}.000Z",
            10 + n / 60,
            n % 60
        )),
    );
    obj.insert("sessionId".into(), json!(SESSION));
    obj.insert(
        "uuid".into(),
        json!(format!("00000000-0000-4000-8000-{n:012}")),
    );
    v
}

// ---- record helpers (the spec's Requirements shorthand) ----

fn human(text: &str) -> Value {
    json!({"type": "user", "origin": {"kind": "human"},
           "message": {"role": "user", "content": text}})
}

fn end_turn() -> Value {
    json!({"type": "assistant", "message": {"role": "assistant", "stop_reason": "end_turn",
           "content": [{"type": "text", "text": "Done."}]}})
}

fn caveat() -> Value {
    json!({"type": "user", "isMeta": true, "message": {"role": "user", "content":
        "<local-command-caveat>Caveat: The messages below were generated by the user while \
         running local commands. DO NOT respond to these messages or otherwise consider them \
         in your response unless the user explicitly asks you to.</local-command-caveat>"}})
}

fn u_wrapper(name: &str) -> Value {
    json!({"type": "user", "message": {"role": "user", "content": format!(
        "<command-name>/{name}</command-name>\n            <command-message>{name}</command-message>\n            <command-args></command-args>"
    )}})
}

/// A user-form `<local-command-stdout>` whose text is padded so the whole JSONL line is
/// about 3 KiB, the measured maximum output line.
fn u_output_padded() -> Value {
    let pad = "x".repeat(3 * 1024 - 160);
    json!({"type": "user", "message": {"role": "user", "content": format!(
        "<local-command-stdout>Set model to opus {pad}</local-command-stdout>"
    )}})
}

/// `human prompt → end_turn` followed by `groups` × `caveat → U-wrapper(/model) → U-output`.
/// Returns the whole log and the byte length of the local-command groups alone.
fn wide_log(groups: usize) -> (String, usize) {
    let mut n = 0;
    let mut next = |v: Value| {
        n += 1;
        stamped(v, n)
    };
    let head = lines(&[
        next(human("Rename the helper and run the tests.")),
        next(end_turn()),
    ]);
    let mut tail_records = Vec::new();
    for _ in 0..groups {
        tail_records.push(next(caveat()));
        tail_records.push(next(u_wrapper("model")));
        tail_records.push(next(u_output_padded()));
    }
    let tail = lines(&tail_records);
    let groups_len = tail.len();
    (format!("{head}{tail}"), groups_len)
}

#[test]
fn r3_1_wider_read_on_a_skipped_only_tail() {
    let (body, groups_len) = wide_log(4);
    assert!(
        groups_len as u64 > TAIL_CAP,
        "the local-command groups must exceed TAIL_CAP ({TAIL_CAP}) or the test proves \
         nothing: they are {groups_len} bytes"
    );
    let p = write("r3_1", &body);
    assert_eq!(
        tail_state(&p).expect("tail").last,
        Some(LastMessage::AssistantEndTurn),
        "the end_turn before a run of local commands larger than the tail is what the card reads"
    );
}

/// The same requirement with the run's length varied, so the tail's cut lands at different
/// points inside a group (on a caveat, a wrapper or an output).
#[test]
fn r3_1_wider_read_holds_wherever_the_tail_cuts_the_run() {
    for groups in 3..=8 {
        let (body, groups_len) = wide_log(groups);
        assert!(
            groups_len as u64 > TAIL_CAP,
            "{groups} groups must exceed TAIL_CAP ({TAIL_CAP}): they are {groups_len} bytes"
        );
        let p = write(&format!("r3_1_groups_{groups}"), &body);
        assert_eq!(
            tail_state(&p).expect("tail").last,
            Some(LastMessage::AssistantEndTurn),
            "{groups} local-command groups ({groups_len} bytes) after an end_turn"
        );
    }
}
